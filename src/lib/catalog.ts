export function bytes(n: number) {
  return n < 1024
    ? `${n} B`
    : n < 1048576
      ? `${(n / 1024).toFixed(0)} KB`
      : `${(n / 1048576).toFixed(1)} MB`;
}
export function parseRanges(value: string, count: number): number[][] {
  if (!value.trim()) return [Array.from({ length: count }, (_, i) => i)];
  return value.split(',').map((part) => {
    const match = /^\s*(\d+)\s*(?:-\s*(\d+)\s*)?$/.exec(part);
    if (!match) throw new Error('Use page numbers or ranges, like 1-3, 5, 7-9.');
    const a = Number(match[1]),
      b = Number(match[2] ?? match[1]);
    if (a < 1 || b < a || b > count)
      throw new Error(
        `Pages must be between 1 and ${count}, in ascending order within each range.`,
      );
    return Array.from({ length: b - a + 1 }, (_, i) => a + i - 1);
  });
}
export function selectedPages(value: string, count: number) {
  return [...new Set(parseRanges(value, count).flat())];
}
export function escapeHTML(s: string) {
  return s.replace(
    /[&<>"']/g,
    (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[c]!,
  );
}
